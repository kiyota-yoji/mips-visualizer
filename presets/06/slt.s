# 第06回 例3：slt（符号あり）と sltu（符号なし）
# 同じビットの並び 1111…1111 が、符号ありでは −1、符号なしでは 4294967295
.text
main:
    li   $t0, -1           # 1111 1111 … 1111
    li   $t1, 1            # 0000 0000 … 0001
    slt  $t2, $t0, $t1     # 符号ありで比べる：−1 < 1 → 1
    sltu $t3, $t0, $t1     # 符号なしで比べる：4294967295 < 1 → 0
    slti $t4, $t1, 10      # 定数と比べる：1 < 10 → 1

    li   $v0, 10           # exit
    syscall
