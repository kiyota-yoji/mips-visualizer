# 第05回 例3：論理演算とシフト
# 2進数で見ると分かりやすい（「命令の中身」モードで 2進数 表示にする）
.text
main:
    li   $t0, 0x0000000D   # 1101（13）
    li   $t1, 0x00000006   # 0110（6）
    and  $t2, $t0, $t1     # 1101 AND 0110 = 0100
    or   $t3, $t0, $t1     # 1101 OR  0110 = 1111
    nor  $t4, $t0, $zero   # NOT 1101（全部のビットが反対になる）
    sll  $t5, $t0, 2       # 左に 2 ビット = × 4
    srl  $t6, $t0, 1       # 右に 1 ビット = ÷ 2（あまりは捨てる）
    andi $t7, $t0, 1       # いちばん下のビットだけ取り出す（奇数なら 1）

    li   $v0, 10           # exit
    syscall
